/**
 * Postgres schema for one Understanding Graph project.
 *
 * One Postgres *schema* per project, mirroring the one-store.db-per-project
 * layout of the SQLite backend. Design rules, and why:
 *
 *  - Timestamps stay TEXT in 'YYYY-MM-DD HH:MM:SS' UTC form. The engine sorts,
 *    slices and string-compares these values in dozens of places
 *    (getEventLog, getRecentCommits, lock expiry, decay scoring). Promoting
 *    them to timestamptz would change every one of those comparisons; keeping
 *    TEXT keeps the port behaviour-preserving.
 *
 *  - Booleans stay INTEGER. The SQL says `active = 1` and `validated = 0`
 *    throughout; a real boolean column would reject those comparisons.
 *
 *  - No FOREIGN KEY constraints. The SQLite backend never enables
 *    `PRAGMA foreign_keys`, so its FK clauses are inert documentation and the
 *    live corpus contains rows that would violate them (nodes carry
 *    tool_call_id values with an empty tool_calls table). Declaring real FKs
 *    here would reject writes SQLite has always accepted.
 *
 *  - Full-text search replaces the FTS5 virtual table and its three sync
 *    triggers with a GIN expression index over title+understanding. An
 *    expression index rather than a stored tsvector column, because the engine
 *    reads nodes with SELECT * and would otherwise pull a tsvector along on
 *    every read.
 *
 *  - nodes.embedding is pgvector `vector(dim)`, dim from UG_EMBEDDING_DIM.
 */

